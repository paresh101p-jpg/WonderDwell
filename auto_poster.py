#!/usr/bin/env python3
"""
WonderDwell Auto Poster 🏡
Posts daily dream homes & unique architecture to Facebook Page (WonderDwell) & Instagram (@wonder_dwell)
Caption auto-generated by Gemini Vision (gemini-3.1-flash-lite)
Schedule: 4:00 PM IST (10:30 UTC) daily via GitHub Actions
"""

import os
import sys
import json
import random
import requests
import io
import time
from pathlib import Path
from PIL import Image
from google import genai

# ─── CONFIG ──────────────────────────────────────────────────────────────────
SCRIPT_DIR = Path(__file__).parent

def load_token():
    token = os.environ.get("FB_PAGE_ACCESS_TOKEN", "").strip()
    if not token:
        token_file = SCRIPT_DIR / "fb_permanent_token.txt"
        if token_file.exists():
            token = token_file.read_text(encoding="utf-8").strip()
    return token

def load_config():
    cfg_file = SCRIPT_DIR / "fb_config.json"
    with open(cfg_file, "r", encoding="utf-8") as f:
        return json.load(f)

def load_gemini_key():
    key = os.environ.get("GEMINI_API_KEY", "").strip()
    if not key:
        key_file = SCRIPT_DIR / "gemini_key.txt"
        if key_file.exists():
            key = key_file.read_text(encoding="utf-8").strip()
    return key

# ─── IMAGE QUEUE ─────────────────────────────────────────────────────────────
def get_next_image():
    queue_file = SCRIPT_DIR / "images_urls.txt"
    backup_file = SCRIPT_DIR / "images_urls_backup.txt"
    used_file = SCRIPT_DIR / "used_urls.txt"

    # Load used URLs to ensure 100% ZERO DUPLICATES
    used_urls = set()
    if used_file.exists():
        used_urls = {l.strip().lstrip('\ufeff') for l in used_file.read_text(encoding='utf-8').splitlines() if l.strip().lstrip('\ufeff')}

    lines = []
    if queue_file.exists():
        lines = [l.strip().lstrip('\ufeff') for l in queue_file.read_text(encoding='utf-8').splitlines() if l.strip().lstrip('\ufeff')]

    # Filter out any that were already used to guarantee zero duplicates
    lines = [u for u in lines if u not in used_urls]

    # Refill from backup if empty
    if not lines:
        print("Queue empty — refilling from backup pool...")
        if backup_file.exists():
            backup = [l.strip().lstrip('\ufeff') for l in backup_file.read_text(encoding='utf-8').splitlines() if l.strip().lstrip('\ufeff')]
            if backup:
                unused_backup = [u for u in backup if u not in used_urls]
                if not unused_backup:
                    print("All images in pool have been posted once! Resetting cycle...")
                    used_file.write_text("", encoding='utf-8')
                    unused_backup = backup
                random.shuffle(unused_backup)
                lines = unused_backup
                queue_file.write_text("\n".join(lines) + "\n", encoding='utf-8')
                print(f"Refilled {len(lines)} URLs from backup pool.")

    if not lines:
        print("ERROR: No images available in queue or backup!")
        sys.exit(1)

    # Pick completely RANDOMLY (not line-by-line), guaranteed NO DUPLICATES
    idx = random.randrange(len(lines))
    image_url = lines.pop(idx)

    # Immediately update queue file (removes the picked image so it can never be picked again)
    queue_file.write_text("\n".join(lines) + "\n" if lines else "", encoding='utf-8')

    # Append to used_urls.txt
    with open(used_file, "a", encoding='utf-8') as f:
        f.write(image_url + "\n")

    print(f"🎲 Randomly selected image (100% unique): {image_url}")
    print(f"Remaining unused in queue: {len(lines)}")
    return image_url

# ─── GEMINI VISION CAPTION ───────────────────────────────────────────────────
def generate_caption(image_url: str, gemini_key: str) -> str:
    """Use Gemini Vision (gemini-3.1-flash-lite) to analyze home image and generate dream home caption."""

    prompt = """You are an architectural writer and luxury home designer for WonderDwell.

Analyze this dream home image carefully.
Look for any home name, architectural style, or location text written on the image.

Write an inspiring, elegant Instagram & Facebook caption in English with this EXACT structure:

🏡 [NAME / STYLE OF HOME, LOCATION IF VISIBLE]

[2-3 sentences describing the unique architecture, materials, and exterior/interior aesthetic of this residence — e.g. glass walls, cantilever design, organic timber, mountain backdrop, or minimalist luxury]

✨ [2 sentences on what makes living here magical — the lifestyle, serenity, views, or standout design highlights that make it a true dream home]

[6-8 high-engagement architecture & dream home hashtags]

RULES:
- Read the text on the image to accurately identify the home name or style
- Keep total caption between 60-90 words (compact, stylish, engaging)
- English only
- Do NOT use asterisks (*) or bold markdown
- End with hashtags on separate line"""

    headers = {"User-Agent": "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36"}
    try:
        resp = requests.get(image_url, headers=headers, timeout=30)
        resp.raise_for_status()
        img = Image.open(io.BytesIO(resp.content))
    except Exception as e:
        print(f"WARNING: Could not download image for Gemini Vision: {e}")
        return generate_fallback_caption()

    try:
        client = genai.Client(api_key=gemini_key)
        res = client.models.generate_content(
            model="gemini-3.1-flash-lite",
            contents=[img, prompt]
        )
        caption = res.text.strip()
        print("✅ Gemini Vision caption generated successfully")
        print(f"Caption preview:\n{caption[:120]}...\n")
        return caption
    except Exception as e:
        print(f"WARNING: Gemini Vision call failed: {e}")
        return generate_fallback_caption()

def generate_fallback_caption() -> str:
    return """🏡 Extraordinary Dream Home

A masterclass in modern architectural design, this stunning residence seamlessly blends luxury living with surrounding nature. Floor-to-ceiling glass and refined materials create an atmosphere of pure tranquility.

✨ Living here offers an unmatched sanctuary of comfort, elegance, and breathtaking views from dawn till dusk.

#DreamHome #Architecture #LuxuryLiving #ModernHome #ArchitecturalDesign #InteriorDesign #HouseGoals #WonderDwell"""

# ─── FACEBOOK POST ────────────────────────────────────────────────────────────
def post_to_facebook(image_url: str, caption: str, page_id: str, token: str) -> str:
    print("Posting to Facebook Page...")
    url = f"https://graph.facebook.com/v21.0/{page_id}/photos"
    payload = {
        "url": image_url,
        "caption": caption,
        "access_token": token
    }
    r = requests.post(url, data=payload, timeout=60)
    result = r.json()
    if "id" in result:
        post_id = result["id"]
        print(f"✅ Facebook Post ID: {post_id}")
        return post_id
    else:
        print(f"⚠️ URL method error: {result}, trying direct byte upload...")
        try:
            h = {"User-Agent": "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36"}
            img_resp = requests.get(image_url, headers=h, timeout=30)
            if img_resp.status_code == 200:
                files = {"source": ("home.jpg", img_resp.content, "image/jpeg")}
                data = {"caption": caption, "access_token": token}
                r_byte = requests.post(url, data=data, files=files, timeout=60)
                res_byte = r_byte.json()
                if "id" in res_byte:
                    post_id = res_byte["id"]
                    print(f"✅ Facebook Post ID (direct upload): {post_id}")
                    return post_id
                else:
                    print(f"❌ Facebook Direct Upload Error: {res_byte}")
        except Exception as e:
            print(f"❌ Fallback upload exception: {e}")
        return None

# ─── INSTAGRAM POST ──────────────────────────────────────────────────────────
def post_to_instagram(image_url: str, caption: str, ig_account_id: str, token: str) -> str:
    print("Posting to Instagram...")

    # Step 1: Create media container
    container_url = f"https://graph.facebook.com/v21.0/{ig_account_id}/media"
    container_payload = {
        "image_url": image_url,
        "caption": caption,
        "access_token": token
    }
    r1 = requests.post(container_url, data=container_payload, timeout=60)
    result1 = r1.json()

    if "id" not in result1:
        print(f"❌ Instagram Container Error: {result1}")
        return None

    container_id = result1["id"]
    print(f"Instagram container created: {container_id}")

    # Step 2: Wait for processing
    time.sleep(5)

    # Step 3: Publish
    publish_url = f"https://graph.facebook.com/v21.0/{ig_account_id}/media_publish"
    publish_payload = {
        "creation_id": container_id,
        "access_token": token
    }
    r2 = requests.post(publish_url, data=publish_payload, timeout=60)
    result2 = r2.json()

    if "id" in result2:
        media_id = result2["id"]
        print(f"✅ Instagram Media ID: {media_id}")
        return media_id
    else:
        print(f"❌ Instagram Publish Error: {result2}")
        return None

# ─── MAIN ────────────────────────────────────────────────────────────────────
def main():
    print("=" * 60)
    print("🏡 WonderDwell Auto Poster Starting...")
    print("=" * 60)

    token = load_token()
    config = load_config()
    gemini_key = load_gemini_key()

    if not token:
        print("ERROR: FB_PAGE_ACCESS_TOKEN not found!")
        sys.exit(1)

    page_id = config["fb_page_id"]
    ig_account_id = config["ig_account_id"]

    print(f"FB Page ID: {page_id}")
    print(f"IG Account ID: {ig_account_id}")

    # Get next image
    image_url = get_next_image()

    # Generate caption via Gemini Vision
    print("\nGenerating caption with Gemini Vision...")
    caption = generate_caption(image_url, gemini_key)
    print(f"\nFinal Caption:\n{caption}\n")

    # Post to both platforms
    print("-" * 40)
    fb_post_id = post_to_facebook(image_url, caption, page_id, token)
    print("-" * 40)
    ig_media_id = post_to_instagram(image_url, caption, ig_account_id, token)

    print("\n" + "=" * 60)
    print("📊 POSTING SUMMARY")
    print("=" * 60)
    print(f"Facebook: {'✅ SUCCESS - ' + str(fb_post_id) if fb_post_id else '❌ FAILED'}")
    print(f"Instagram: {'✅ SUCCESS - ' + str(ig_media_id) if ig_media_id else '❌ FAILED'}")
    print("=" * 60)

    if not fb_post_id and not ig_media_id:
        print("Both platforms failed — exiting with error")
        sys.exit(1)

    print("🏡 WonderDwell post complete!")

if __name__ == "__main__":
    main()

